"""Check the tutor against the gold-standard questions.

    python -m scholariq.answering.evaluate [--out ../docs/eval/answers.md]

Cases live in ``content/eval/answers.yaml``. A case passes only if every
expectation it states holds: status, handler, concepts (in order), required
section kinds, exact solver result, required text. Results are reported for
the cases used while building the engine ("tuning") and, separately, for cases
written afterwards ("held out"), because only the second group says anything
about questions the engine has not been fitted to.
"""

from __future__ import annotations

import argparse
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path
from typing import Literal

import yaml
from pydantic import BaseModel, ConfigDict, Field

from scholariq.answering.engine import Engine, Request
from scholariq.answering.model import Answer
from scholariq.nlu.parser import Context


class GoldCase(BaseModel):
    model_config = ConfigDict(extra="forbid")
    q: str
    group: Literal["tuning", "held_out"]
    status: Literal["answered", "clarify", "abstained"]
    handler: str | None = None
    concepts: list[str] | None = None
    concepts_include: list[str] = Field(default_factory=list)
    sections: list[str] = Field(default_factory=list)
    result: str | None = None
    contains: str | None = None
    after: list[str] = Field(default_factory=list)


class GoldFile(BaseModel):
    model_config = ConfigDict(extra="forbid")
    version: int
    cases: list[GoldCase]


@dataclass
class GoldResult:
    case: GoldCase
    answer: Answer
    problems: list[str]

    @property
    def passed(self) -> bool:
        return not self.problems


def load_cases(path: Path) -> list[GoldCase]:
    return GoldFile.model_validate(yaml.safe_load(path.read_text(encoding="utf-8"))).cases


def _text(a: Answer) -> str:
    parts = []
    for s in a.sections:
        parts += [s.title, s.text or "", *s.steps, *(c for r in s.rows for c in r)]
        parts += [i.text for i in s.items]
    return "\n".join(parts)


def check(case: GoldCase, a: Answer) -> list[str]:
    problems = []
    if a.status != case.status:
        problems.append(f"status {a.status}, expected {case.status}")
    if case.handler and a.handler != case.handler:
        problems.append(f"handler {a.handler}, expected {case.handler}")
    slugs = [c.slug for c in a.concepts]
    if case.concepts is not None and slugs[: len(case.concepts)] != case.concepts:
        problems.append(f"concepts {slugs[:3]}, expected {case.concepts}")
    missing = [c for c in case.concepts_include if c not in slugs]
    if missing:
        problems.append(f"concepts missing {missing}")
    kinds = {s.kind for s in a.sections}
    if lacking := [k for k in case.sections if k not in kinds]:
        problems.append(f"no {', '.join(lacking)} section")
    if case.result is not None:
        got = next((s.text for s in a.sections if s.title == "Answer"), None)
        if got != case.result:
            problems.append(f"result {got!r}, expected {case.result!r}")
    if case.contains and case.contains not in _text(a):
        problems.append(f"does not contain {case.contains!r}")
    return problems


def run(engine: Engine, cases: list[GoldCase]) -> list[GoldResult]:
    out = []
    for case in cases:
        context: Context | None = None
        for earlier in case.after:
            context = engine.answer(Request(earlier, context)).context
        answer = engine.answer(Request(case.q, context)).answer
        out.append(GoldResult(case, answer, check(case, answer)))
    return out


def report(results: list[GoldResult]) -> str:
    groups: dict[str, list[GoldResult]] = defaultdict(list)
    for r in results:
        groups[r.case.group].append(r)
    lines = [
        "# Answer evaluation",
        "",
        "Generated by `python -m scholariq.answering.evaluate`; do not edit by hand.",
        "",
        "Each gold question states what a correct answer must be (status, handler, concepts,",
        "required sections, exact solver result). A case passes only if all of it holds.",
        "",
        '"Tuning" cases were used while building the engine and choosing its thresholds,',
        'so they overstate quality. "Held out" cases were written afterwards and are the',
        "more honest measure. Both sets were written by the same author as the content.",
        "A held-out case that fails and is then fixed moves to tuning, so the held-out",
        "figure never includes questions the engine was changed to pass.",
        "",
        "| Group | Cases | Passed | Answered correctly | Declined correctly "
        "| Clarified correctly |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for name in ("tuning", "held_out"):
        rs = groups.get(name, [])
        if not rs:
            continue

        def rate(status: str, rs: list[GoldResult] = rs) -> str:
            sub = [r for r in rs if r.case.status == status]
            return f"{sum(r.passed for r in sub)} of {len(sub)}" if sub else "-"

        lines.append(
            f"| {name.replace('_', ' ')} | {len(rs)} | {sum(r.passed for r in rs)} "
            f"| {rate('answered')} | {rate('abstained')} | {rate('clarify')} |"
        )
    wrong_answers = [
        r for r in results if r.case.status == "abstained" and r.answer.status == "answered"
    ]
    lines += [
        "",
        f"Questions that should have been declined but were answered: {len(wrong_answers)}.",
        "",
        "## Failures",
        "",
    ]
    failures = [r for r in results if not r.passed]
    if not failures:
        lines.append("None.")
    else:
        lines += ["| Group | Question | Problem |", "|---|---|---|"]
        for r in failures:
            q = r.case.q.split("\n")[0].replace("|", "\\|")
            lines.append(f"| {r.case.group} | {q} | {'; '.join(r.problems)} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> None:
    from scholariq.core.config import get_settings
    from scholariq.knowledge.evaluate import seed_session
    from scholariq.knowledge.index import build_index
    from scholariq.nlu.lexicon import build_lexicon

    parser = argparse.ArgumentParser(description="Evaluate the tutor's answers.")
    parser.add_argument("--out", type=Path, help="write the Markdown report here")
    args = parser.parse_args(argv)
    content_dir = get_settings().content_dir
    with seed_session(content_dir) as session:
        index = build_index(session, allow_unreviewed=True)
        engine = Engine(session, build_lexicon(session, index, content_dir), allow_unreviewed=True)
        results = run(engine, load_cases(content_dir / "eval/answers.yaml"))
    text = report(results)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
