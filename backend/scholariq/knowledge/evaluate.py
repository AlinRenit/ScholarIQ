"""Measure knowledge-base search against a fixed set of student-style queries.

    python -m scholariq.knowledge.evaluate [--out ../docs/eval/retrieval.md]

The evaluation set lives in ``content/eval/retrieval.yaml``. Each case lists the
concept(s) a correct search should rank first; out-of-scope cases expect no
results. The report gives hit@1, hit@3 and mean reciprocal rank per kind of
query, and lists every miss with what was returned instead, so weaknesses are
visible rather than averaged away.
"""

from __future__ import annotations

import argparse
import tempfile
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path
from typing import Literal

import yaml
from pydantic import BaseModel, ConfigDict
from sqlalchemy.orm import Session

from scholariq.knowledge.index import ConceptIndex

Kind = Literal["name", "alias", "paraphrase", "misspelling", "out_of_scope"]
KINDS: tuple[Kind, ...] = ("name", "alias", "paraphrase", "misspelling", "out_of_scope")


class EvalCase(BaseModel):
    model_config = ConfigDict(extra="forbid")
    q: str
    expect: list[str]
    kind: Kind


class EvalFile(BaseModel):
    model_config = ConfigDict(extra="forbid")
    version: int
    cases: list[EvalCase]


@dataclass
class CaseResult:
    case: EvalCase
    returned: list[str]
    rank: int | None  # 1-based rank of the first expected concept; None if absent

    @property
    def passed(self) -> bool:
        if self.case.kind == "out_of_scope":
            return not self.returned
        return self.rank == 1


@dataclass
class Summary:
    cases: int
    hit1: float
    hit3: float
    mrr: float


def load_cases(path: Path) -> list[EvalCase]:
    return EvalFile.model_validate(yaml.safe_load(path.read_text())).cases


def run(index: ConceptIndex, cases: list[EvalCase], k: int = 10) -> list[CaseResult]:
    known = {c.slug for c in index.concepts.values()}
    results = []
    for case in cases:
        unknown = [s for s in case.expect if s not in known]
        if unknown:
            raise ValueError(f"{case.q!r} expects unknown concept(s): {', '.join(unknown)}")
        returned = [h.concept.slug for h in index.search(case.q, k)]
        rank = next((i + 1 for i, s in enumerate(returned) if s in case.expect), None)
        results.append(CaseResult(case, returned, rank))
    return results


def summarise(results: list[CaseResult]) -> Summary:
    n = len(results)
    if n == 0:
        return Summary(0, 0.0, 0.0, 0.0)
    return Summary(
        cases=n,
        hit1=sum(r.rank == 1 for r in results) / n,
        hit3=sum(r.rank is not None and r.rank <= 3 for r in results) / n,
        mrr=sum(1 / r.rank for r in results if r.rank) / n,
    )


def report(results: list[CaseResult]) -> str:
    by_kind: dict[str, list[CaseResult]] = defaultdict(list)
    for r in results:
        by_kind[r.case.kind].append(r)
    ranked = [r for r in results if r.case.kind != "out_of_scope"]
    oos = by_kind.get("out_of_scope", [])

    lines = [
        "# Retrieval evaluation",
        "",
        "Generated by `python -m scholariq.knowledge.evaluate`; do not edit by hand.",
        "",
        "Search is BM25 over concept names, definitions and explanations plus a bonus when",
        "the query names a concept. A case counts as a hit at k when an expected concept is",
        "in the top k results. Out-of-scope queries pass only when search returns nothing.",
        "",
        "Caveat: the cases were written by the same author as the seed content, after it was",
        "written, so name and alias scores are optimistic. Paraphrases, misspellings and",
        "out-of-scope queries are the more honest signal. Search alone does not decide whether",
        "the tutor answers; the tutor adds its own abstention checks on top.",
        "",
        "| Query kind | Cases | Hit@1 | Hit@3 | MRR |",
        "|---|---:|---:|---:|---:|",
    ]
    for kind in KINDS:
        if kind == "out_of_scope" or kind not in by_kind:
            continue
        s = summarise(by_kind[kind])
        lines.append(f"| {kind} | {s.cases} | {s.hit1:.0%} | {s.hit3:.0%} | {s.mrr:.2f} |")
    s = summarise(ranked)
    lines.append(f"| **all in scope** | {s.cases} | {s.hit1:.0%} | {s.hit3:.0%} | {s.mrr:.2f} |")
    if oos:
        empty = sum(r.passed for r in oos)
        lines += ["", f"Out of scope: {empty} of {len(oos)} queries correctly returned nothing."]

    misses = [r for r in results if not r.passed]
    lines += ["", "## Misses", ""]
    if not misses:
        lines.append("None.")
    else:
        lines += ["| Kind | Query | Expected | Rank | Returned first |", "|---|---|---|---:|---|"]
        for r in misses:
            first = ", ".join(r.returned[:3]) or "nothing"
            rank = str(r.rank) if r.rank else "–" if r.case.kind == "out_of_scope" else "> 10"
            expected = ", ".join(r.case.expect) or "nothing"
            lines.append(f"| {r.case.kind} | {r.case.q} | {expected} | {rank} | {first} |")
    return "\n".join(lines) + "\n"


def _build_seed_index(content_dir: Path) -> ConceptIndex:
    """Load the seed content into a throwaway SQLite database and index it."""
    from scholariq.curriculum.sync import load_files, sync_curricula
    from scholariq.db import models  # noqa: F401  (registers tables)
    from scholariq.db.base import Base
    from scholariq.db.session import build_engine
    from scholariq.knowledge.index import build_index
    from scholariq.knowledge.loader import load_content
    from scholariq.knowledge.sync import sync_knowledge

    with tempfile.TemporaryDirectory() as tmp:
        engine = build_engine(f"sqlite:///{tmp}/eval.sqlite")
        Base.metadata.create_all(engine)
        with Session(engine) as session:
            sync_curricula(session, load_files(content_dir))
            sync_knowledge(session, load_content(content_dir))
            index = build_index(session, allow_unreviewed=True)
        engine.dispose()
    return index


def main(argv: list[str] | None = None) -> None:
    from scholariq.core.config import get_settings

    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", type=Path, help="write the Markdown report here")
    args = parser.parse_args(argv)
    content_dir = get_settings().content_dir
    results = run(_build_seed_index(content_dir), load_cases(content_dir / "eval/retrieval.yaml"))
    text = report(results)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text)
    print(text)


if __name__ == "__main__":
    main()
